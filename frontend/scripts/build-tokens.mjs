// Builds src/app/styles/tokens.css from the DTCG files in tokens/.
// Light values live on :root; dark values apply for [data-theme=dark] and for the system preference
// unless the user forced light. Text styles become .text-* classes, mobile-first.
import { writeFile } from 'node:fs/promises'
import StyleDictionary from 'style-dictionary'

const DESKTOP = '(width >= 1024px)'
const OUT = new URL('../src/app/styles/tokens.css', import.meta.url)

async function tokensOf(source) {
  const sd = new StyleDictionary({
    source,
    usesDtcg: true,
    log: { verbosity: 'silent' },
    platforms: { css: { transformGroup: 'css', options: { outputReferences: false } } },
  })
  const { allTokens } = await sd.getPlatformTokens('css')
  return allTokens
}

const decl = (token) => `  --${token.name}: ${token.$value};`

const base = await tokensOf(['tokens/base.json', 'tokens/color.light.json'])
const dark = await tokensOf(['tokens/color.dark.json'])

const vars = base.filter((t) => t.$type !== 'typography')
const typography = base.filter((t) => t.$type === 'typography')

const darkBlock = [...dark.map(decl), '  --shadow-overlay: none;', '  color-scheme: dark;'].join('\n')

const textClasses = typography.flatMap((token) => {
  const name = token.path.at(-1)
  const value = token.original.$value
  const family = String(value.fontFamily).replace(/^\{font\.(\w+)\}$/, 'var(--font-$1)')
  const mobile = token.original.$extensions?.['app.mobile']
  const rules = [
    `.text-${name} {`,
    `  font-family: ${family};`,
    `  font-size: ${mobile?.fontSize ?? value.fontSize};`,
    `  line-height: ${mobile?.lineHeight ?? value.lineHeight};`,
    `  font-weight: ${value.fontWeight};`,
    `  letter-spacing: ${value.letterSpacing};`,
    '}',
  ]
  if (mobile) {
    rules.push(
      `@media ${DESKTOP} {`,
      `  .text-${name} {`,
      `    font-size: ${value.fontSize};`,
      `    line-height: ${value.lineHeight};`,
      '  }',
      '}',
    )
  }
  return rules
})

const css = [
  '/* Generated by scripts/build-tokens.mjs from tokens/*.json. Do not edit. */',
  ':root {',
  ...vars.map(decl),
  '  color-scheme: light;',
  '}',
  '',
  '@media (prefers-color-scheme: dark) {',
  "  :root:not([data-theme='light']) {",
  darkBlock.replaceAll(/^/gm, '  '),
  '  }',
  '}',
  '',
  ":root[data-theme='dark'] {",
  darkBlock,
  '}',
  '',
  ...textClasses,
  '',
].join('\n')

await writeFile(OUT, css)
console.log(`tokens.css: ${vars.length} variables, ${dark.length} dark overrides, ${typography.length} text styles`)
